"""Mock-backend label: every role that sees generated text is told it is placeholder output (deployment demo)."""

from __future__ import annotations

import dataclasses

import pytest

from app.web.main import create_app
from conftest import Site

BANNER = "Placeholder output from the mock backend. Not generated by the language model."
ROLES = ("owner", "caregiver", "patient", "child")
# a page that shows generated text for each role: the dashboard, and the summaries tab that role can open
PAGES = {"owner": ("", "/summaries?tab=patient", "/summaries?tab=caregiver", "/summaries?tab=child"),
         "caregiver": ("", "/summaries?tab=patient", "/summaries?tab=caregiver", "/summaries?tab=child"),
         "patient": ("", "/summaries?tab=patient"),
         "child": ("", "/summaries?tab=child")}


@pytest.mark.parametrize("role", ROLES)
def test_banner_is_shown_to_every_role_in_mock_mode(full, role):
    assert full.p is not None
    for suffix in PAGES[role]:
        r = full.site[role].get(f"/p/{full.pid}{suffix}")
        assert r.status_code == 200, (role, suffix)
        assert BANNER in r.text, (role, suffix)


def test_banner_appears_once_per_output_card_not_in_the_footer_or_elsewhere(full):
    html = full.site["child"].get(f"/p/{full.pid}").text
    assert html.count(BANNER) == 1
    assert html.index(BANNER) < html.index("<footer")


@pytest.mark.parametrize("role", ROLES)
def test_banner_is_absent_with_the_real_backend(full, settings, ctx, runner, role):
    """Same database, but the app is configured with APP_BACKEND=llama_cpp (no model is loaded by these requests)."""
    real = dataclasses.replace(settings, backend="llama_cpp")
    app = create_app(real, ctx=ctx, runner=runner, start_worker=False)
    email = full.users[role]["email"]
    s = Site(app)
    assert s.login(email).status_code == 303
    for suffix in PAGES[role]:
        r = s.get(f"/p/{full.pid}{suffix}")
        assert r.status_code == 200 and "Prototype. Not for real patient data." in r.text, (role, suffix)
        assert "Placeholder output" not in r.text and "mock backend" not in r.text, (role, suffix)


def test_pages_without_generated_text_do_not_carry_the_banner(full):
    for url in ("/settings", f"/p/{full.pid}/circle", "/profiles", "/"):
        assert BANNER not in full.site["owner"].get(url).text, url
